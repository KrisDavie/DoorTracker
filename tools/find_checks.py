"""Write data/checks.py: the dungeon checks the tracker shows, and the memory flag each one sets when collected.

Usage: uv run tools/find_checks.py PATH_TO_WORLD
PATH_TO_WORLD is the door randomizer's Archipelago world (worlds/alttpr), which holds RomAddresses.py and the
randomizer itself in ALttPDoorRandomizer/. Where each check is drawn comes from data/new_location_data.py.

Chests, bosses and prizes set a bit in the room's save data. A key in a pot or dropped by an enemy sets a bit
in the randomizer's own pot or enemy table, numbered by the pot's or enemy's place in the room; the room's
"key taken" bit is listed for those as well, in case a version of the rom sets that instead.
"""

import ast
import importlib
import sys
import types
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from data.new_location_data import underworld_items  # noqa: E402
from gui.Doors.rooms import SUPERTILES  # noqa: E402

KINDS = ("chest", "key_pot", "drop", "prize")


def literal(path: Path, name: str):
    """A dict assigned at the top of a python file, read without running the file."""
    for node in ast.parse(path.read_text(encoding="utf-8")).body:
        if isinstance(node, ast.Assign) and any(isinstance(t, ast.Name) and t.id == name for t in node.targets):
            return ast.literal_eval(node.value)
    raise SystemExit(f"{path} has no {name}")


def key_drop_bits(randomizer: Path) -> dict[str, tuple[str, tuple[str, int, int]]]:
    """Name the key drop is drawn under -> (its name as a check, (table, room, mask)).

    The bits are worked out as the randomizer's client does. The position data lists a key in a pot under the
    pot's own name, "<room> Pot #<n>", which is also how the randomizer names its pots.
    """
    # This copy of the randomizer imports Archipelago's Utils by bare name, for a function the tables do not use
    stand_in = types.ModuleType("Utils")
    setattr(stand_in, "parse_yaml", None)
    sys.modules.setdefault("Utils", stand_in)
    sys.path.insert(0, str(randomizer.parent))
    pots = importlib.import_module(f"{randomizer.name}.PotShuffle")
    key = importlib.import_module(f"{randomizer.name}.BaseClasses").PotItem.Key
    enemies = importlib.import_module(f"{randomizer.name}.source.rom.DataTables").get_uw_enemy_table().room_map
    bits = {}
    for name, data in pots.key_drop_data.items():
        if data[0] == "Pot":
            room = data[1]
            (index,) = [k for k, pot in enumerate(pots.vanilla_pots[room]) if pot.item == key]
            bits[f"{pots.vanilla_pots[room][index].room} Pot #{index + 1}"] = (name, ("pot", room, 0x8000 >> index))
        else:
            _, room, index = data[1]
            # Overlords are in the enemy list but have no bit
            index -= sum(1 for sprite in enemies[room][:index] if sprite.sub_type == 0x07)
            bits[name] = (name, ("enemy", room, 0x8000 >> index))
    return bits


def main() -> None:
    world = Path(sys.argv[1]).resolve()
    room_flags = literal(world / "RomAddresses.py", "location_table_uw")
    prize_flags = literal(world / "RomAddresses.py", "location_table_boss")
    drops = key_drop_bits(world / "ALttPDoorRandomizer")

    checks: dict[str, tuple[tuple[int, int], int, int, list[tuple[str, int, int]]]] = {}  # tile, x, y, flags
    unplaced = []
    for tile, spots in sorted(underworld_items.items()):
        if tile not in SUPERTILES:
            continue
        room = tile[1] * 16 + tile[0]
        for name, spot in spots.items():
            if spot["loc_type"] not in KINDS:
                continue
            flags: list[tuple[str, int, int]] = []
            if name in drops:
                name, flag = drops[name]
                flags.append(flag)
            if name in room_flags:
                assert room_flags[name][0] == room, f"{name}: drawn in room {room:#x}, flagged in {room_flags[name][0]:#x}"
                flags.append(("room", room, room_flags[name][1]))
            if name in prize_flags:
                flags.append(("prize", 0, prize_flags[name]))
            if not flags:
                unplaced.append(name)
                continue
            checks[name] = (tile, int(spot["x"]), int(spot["y"]), flags)

    in_dungeons = [n for n, (room, _) in room_flags.items() if (room % 16, room // 16) in SUPERTILES]
    flagged = set(in_dungeons) | set(prize_flags) | {name for name, _ in drops.values()}
    print(f"{len(checks)} checks written")
    print("drawn but with no flag:", unplaced)
    print("flagged in a dungeon room but not drawn:", sorted(flagged - set(checks)))

    lines = [
        '"""Dungeon checks: where each is drawn and the memory flag it sets when collected.',
        "",
        "Generated by tools/find_checks.py from the door randomizer's tables (MIT licence, (c) LLCoolDave and",
        "contributors) and data/new_location_data.py. Do not edit by hand.",
        "",
        "flags: (table, room, mask). The check is collected when any of them is set. Tables:",
        '  "room"   the room\'s word of save data',
        '  "pot"    the room\'s word of the randomizer\'s pot table',
        '  "enemy"  the room\'s word of the randomizer\'s enemy drop table',
        '  "prize"  the dungeon prizes word; room is unused',
        '"""',
        "",
        "from typing import TypedDict",
        "",
        "",
        "class Check(TypedDict):",
        "    tile: tuple[int, int]  # supertile",
        "    x: int  # position in the supertile, 0..512",
        "    y: int",
        "    flags: list[tuple[str, int, int]]",
        "",
        "",
        "checks: dict[str, Check] = {",
    ]
    for name, (tile, x, y, flags) in checks.items():
        listed = ", ".join(f'("{table}", {room:#04x}, {mask:#06x})' for table, room, mask in flags)
        lines.append(f'    {name!r}: {{"tile": {tile}, "x": {x}, "y": {y}, "flags": [{listed}]}},')
    lines.append("}")
    (ROOT / "data" / "checks.py").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
